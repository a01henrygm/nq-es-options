def _s(text) -> str:
    """Strip characters that would break a Pine string or comment line."""
    return re.sub(r"\s+", " ", re.sub(r'["\\]', "", str(text))).strip()


def _f(x) -> str:
    return "na" if x is None else f"{float(x):.2f}"


def _q(x) -> str:
    return f'"{_s(x)}"'


def _big(v: float) -> str:
    a = abs(v)
    for lim, suf in ((1e12, "T"), (1e9, "B"), (1e6, "M"), (1e3, "K")):
        if a >= lim:
            return f"{v / lim:.1f}{suf}"
    return f"{v:,.0f}"


def build_heatmap_pine(strikes: list, measures: dict, source: str, units: str, window_text: str, expiries_text: str,
                       snap_et=None, default_measure: str = "all", default_side: str = "total") -> str:
    """strikes: ascending prices in chart units, shared by every measure.
    measures: key -> {"available": bool, "note": str, "call": [..], "put": [..] (aligned to strikes, chart-independent values),
                      "units": str, "sides": {side: {"hot_spots": [{rank, price, low, high, share, meaning, value, top_expiry}],
                                                     "center": float|None, "share_above", "share_below", "summary": str}}}"""
    n = len(strikes)
    if n == 0:                      # array.from() needs at least one element; a lone zero row is never drawn
        strikes = [0.0]
        n = 1
    parts = []
    avail, notes = [], []
    hs = {k: [] for k in ("key", "side", "rank", "price", "low", "high", "share", "text")}
    ct = {k: [] for k in ("key", "side", "price", "above", "below", "sum")}
    for key in MEASURE_KEYS:
        m = measures.get(key) or {"available": False, "note": "Not exported."}
        ok = bool(m.get("available"))
        avail.append("true" if ok else "false")
        notes.append(_q(m.get("note") or ""))
        call = list(m.get("call") or []) if ok else []
        put = list(m.get("put") or []) if ok else []
        call = (call + [0.0] * n)[:n]
        put = (put + [0.0] * n)[:n]
        top = max([abs(v) for v in call + put] + [abs(c + p) for c, p in zip(call, put)] + [abs(c - p) for c, p in zip(call, put)] + [0.0])
        sc = (SCALE / top) if top > 0 else 0.0
        suf = MEASURE_INFO[key][2]
        parts.append(f"var int[] c{suf} = array.from({', '.join(str(int(round(v * sc))) for v in call)})")
        parts.append(f"var int[] p{suf} = array.from({', '.join(str(int(round(v * sc))) for v in put)})")
        if not ok:
            continue
        for side, sd in (m.get("sides") or {}).items():
            for h in sd.get("hot_spots") or []:
                hs["key"].append(_q(key))
                hs["side"].append(_q(side))
                hs["rank"].append(str(int(h["rank"])))
                hs["price"].append(_f(h["price"]))
                hs["low"].append(_f(h["low"]))
                hs["high"].append(_f(h["high"]))
                hs["share"].append(f"{float(h.get('share') or 0):.4f}")
                exp = f", {h['top_expiry'][5:]}" if h.get("top_expiry") else ""
                size = f" ({_big(h['value'])})" if key in MODELED and h.get("value") is not None else ""
                hs["text"].append(_q(f"{h.get('meaning') or ''}{size}{exp}"))
            ct["key"].append(_q(key))
            ct["side"].append(_q(side))
            ct["price"].append(_f(sd.get("center")))
            ct["above"].append("na" if sd.get("share_above") is None else f"{sd['share_above']:.4f}")
            ct["below"].append("na" if sd.get("share_below") is None else f"{sd['share_below']:.4f}")
            ct["sum"].append('"' + "\\n".join(textwrap.wrap(_s(sd.get("summary") or ""), 64)) + '"')     # \n breaks the line in the table
    if not hs["key"]:
        hs = {"key": ['"none"'], "side": ['"none"'], "rank": ["99"], "price": ["0.0"], "low": ["0.0"], "high": ["0.0"], "share": ["0.0"], "text": ['""']}
    if not ct["key"]:
        ct = {"key": ['"none"'], "side": ['"none"'], "price": ["na"], "above": ["na"], "below": ["na"], "sum": ['""']}
    # na cannot start an array.from() of floats (its type would be unknown), so lead with a typed first element when needed
    for arr in (ct["price"], ct["above"], ct["below"], hs["price"], hs["low"], hs["high"]):
        if arr and arr[0] == "na":
            arr[0] = "float(na)"
    snap = ('timestamp("America/New_York", %d, %d, %d, %d, %d, 0)' % (snap_et.year, snap_et.month, snap_et.day, snap_et.hour, snap_et.minute)) if snap_et else "na"
    rep = {
        "__SOURCE__": _s(source), "__UNITS__": _s(units), "__WINDOW__": _s(window_text), "__EXPIRIES__": _s(expiries_text),
        "__SOURCE_SHORT__": _s(source)[:120], "__UNITS_SHORT__": _s(units)[:120],
        "__DEF_MEASURE__": "Combined (all measures)" if default_measure in ("all", "combined") else MEASURE_INFO.get(default_measure, MEASURE_INFO["volume"])[0], "__DEF_SIDE__": SIDE_NAMES.get(default_side, "Calls + puts"),
        "__SNAPTIME__": snap, "__STRIKES__": ", ".join(f"{float(k):.2f}" for k in strikes),
        "__AVAIL__": ", ".join(avail), "__NOTES__": ", ".join(notes), "__PROFILE_ARRAYS__": "\n".join(parts),
        "__HS_KEY__": ", ".join(hs["key"]), "__HS_SIDE__": ", ".join(hs["side"]), "__HS_RANK__": ", ".join(hs["rank"]),
        "__HS_PRICE__": ", ".join(hs["price"]), "__HS_LOW__": ", ".join(hs["low"]), "__HS_HIGH__": ", ".join(hs["high"]),
        "__HS_SHARE__": ", ".join(hs["share"]), "__HS_TEXT__": ", ".join(hs["text"]),
        "__CT_KEY__": ", ".join(ct["key"]), "__CT_SIDE__": ", ".join(ct["side"]), "__CT_PRICE__": ", ".join(ct["price"]),
        "__CT_ABOVE__": ", ".join(ct["above"]), "__CT_BELOW__": ", ".join(ct["below"]), "__CT_SUM__": ", ".join(ct["sum"]),
    }
    out = HEADER
    for k, v in rep.items():
        out = out.replace(k, v)
    return out + BODY.replace("__INK__", "\n".join(INK_FUNCS))
